"""SAM 2.1 local checkpoints and SAM3 sidecar inference.

SAM2 runs in GUI env. SAM3 runs in a separate Python env, launched per request.
Never automatically download or modify SAM weights here.
"""
from __future__ import annotations

import os
import json
import subprocess
import sys
import tempfile
from contextlib import nullcontext
from pathlib import Path

import numpy as np
from PIL import Image

SAM2_CONFIGS = {
    'SAM2.1 tiny': ('configs/sam2.1/sam2.1_hiera_t.yaml', 'sam2.1_hiera_tiny.pt'),
    'SAM2.1 small': ('configs/sam2.1/sam2.1_hiera_s.yaml', 'sam2.1_hiera_small.pt'),
    'SAM2.1 base+': ('configs/sam2.1/sam2.1_hiera_b+.yaml', 'sam2.1_hiera_base_plus.pt'),
    'SAM2.1 large': ('configs/sam2.1/sam2.1_hiera_l.yaml', 'sam2.1_hiera_large.pt'),
}
ROOT = Path(__file__).resolve().parent


def _local_config() -> dict:
    """Optional installation paths generated by setup.ps1 (never commit this file)."""
    path = ROOT / '.local' / 'config.json'
    try:
        return json.loads(path.read_text(encoding='utf-8-sig')) if path.exists() else {}
    except (OSError, ValueError):
        return {}


def _sam2_locations() -> list[Path]:
    config = _local_config()
    candidates = [
        os.environ.get('SEGMENT_STUDIO_SAM2_MODELS'),
        os.environ.get('FIREMASK_SAM2_MODELS'),
        config.get('sam2_models'),
        ROOT / 'models' / 'sam2.1',
        ROOT.parent / 'fire_annotation_poc' / 'models' / 'sam2.1',
    ]
    return [Path(path) for path in candidates if path]


def sam2_dir() -> Path:
    """Show a useful location even before any files are downloaded."""
    for folder in _sam2_locations():
        if any(folder.glob('sam2.1_hiera_*.pt')):
            return folder
    return _sam2_locations()[0]


def sam2_checkpoint(variant: str) -> Path:
    filename = SAM2_CONFIGS[variant][1]
    for folder in _sam2_locations():
        candidate = folder / filename
        if candidate.is_file():
            return candidate
    return _sam2_locations()[0] / filename


def sam3_checkpoint() -> Path:
    config = _local_config()
    candidates = [
        os.environ.get('SEGMENT_STUDIO_SAM3_CKPT'),
        os.environ.get('FIREMASK_SAM3_CKPT'),
        config.get('sam3_checkpoint'),
        ROOT / 'models' / 'sam3' / 'sam3.pt',
        ROOT.parent / 'FireMask_v2_Workspace' / 'models' / 'sam3' / 'sam3.pt',
    ]
    for path in candidates:
        if path and Path(path).is_file():
            return Path(path)
    return Path(next(path for path in candidates if path))


def sam3_python() -> Path:
    config = _local_config()
    candidates = [
        os.environ.get('SEGMENT_STUDIO_SAM3_PYTHON'),
        os.environ.get('FIREMASK_SAM3_PYTHON'),
        config.get('sam3_python'),
    ]
    if sys.platform == 'win32':
        candidates.extend([
            Path(sys.prefix).parent / 'segment_studio_sam3' / 'python.exe',
            Path(sys.prefix).parent / 'firemask_sam3' / 'python.exe',
        ])
    else:
        candidates.extend([
            Path(sys.prefix).parent / 'segment_studio_sam3' / 'bin' / 'python',
            Path(sys.prefix).parent / 'firemask_sam3' / 'bin' / 'python',
        ])
    for path in candidates:
        if path and Path(path).is_file():
            return Path(path)
    return Path(next(path for path in candidates if path))


class Sam2Local:
    def __init__(self):
        self.predictor = None
        self.loaded_model = None
        self.image_key = None

    def clear(self):
        self.predictor = None
        self.loaded_model = None
        self.image_key = None
        import gc
        gc.collect()
        try:
            import torch
            if torch.cuda.is_available():
                torch.cuda.empty_cache()
        except ImportError:
            pass

    def predict(self, variant: str, image: Image.Image, points: list[tuple[int, int, int]], image_key: str) -> Image.Image:
        import torch
        from sam2.build_sam import build_sam2
        from sam2.sam2_image_predictor import SAM2ImagePredictor
        cfg, _ = SAM2_CONFIGS[variant]
        checkpoint = sam2_checkpoint(variant)
        if not checkpoint.is_file():
            raise FileNotFoundError(f'Missing checkpoint: {checkpoint}\nCopy your existing SAM2.1 checkpoints or set FIREMASK_SAM2_MODELS.')
        if checkpoint.stat().st_size < 1_000_000:
            raise RuntimeError(f'Incomplete SAM2 checkpoint: {checkpoint}')
        device = 'cuda' if torch.cuda.is_available() else 'cpu'
        if self.loaded_model != variant or self.predictor is None:
            self.clear()
            sam_model = build_sam2(config_file=cfg, ckpt_path=str(checkpoint), device=device)
            self.predictor = SAM2ImagePredictor(sam_model)
            self.loaded_model = variant
        context = torch.autocast(device_type='cuda', dtype=torch.bfloat16) if device == 'cuda' else nullcontext()
        with torch.inference_mode(), context:
            if self.image_key != image_key:
                self.predictor.set_image(np.asarray(image))
                self.image_key = image_key
            coords = np.asarray([(x, y) for x, y, _ in points], dtype=np.float32)
            labels = np.asarray([cls for _, _, cls in points], dtype=np.int32)
            masks, scores, _ = self.predictor.predict(point_coords=coords, point_labels=labels, multimask_output=True)
        winning = np.asarray(masks[int(np.argmax(scores))], dtype=np.uint8) * 255
        return Image.fromarray(winning, 'L')


def sam3_predict(image_path: Path, prompt: str, threshold: float = 0.4) -> Image.Image:
    """One request in another Conda env. SAM2 env cannot conflict with SAM3 dependencies."""
    python_exe = sam3_python()
    if not python_exe.exists():
        raise FileNotFoundError(f'SAM3 Python not found: {python_exe}\nRun SETUP_WINDOWS.ps1 -WithSAM3 first.')
    checkpoint = sam3_checkpoint()
    if not checkpoint.is_file():
        raise FileNotFoundError(f'SAM3 checkpoint not found: {checkpoint}\nRun SETUP_WINDOWS.ps1 -WithSAM3 after Hugging Face approval.')
    with tempfile.TemporaryDirectory(prefix='firemask_sam3_') as folder:
        result = Path(folder) / 'mask.png'
        command = [str(python_exe), str(ROOT / 'sam3_worker.py'), '--image', str(image_path),
                   '--output', str(result), '--checkpoint', str(checkpoint),
                   '--text', prompt, '--threshold', str(threshold)]
        try:
            run = subprocess.run(command, check=False, capture_output=True, text=True,
                                 encoding='utf-8', errors='replace', timeout=420)
        except subprocess.TimeoutExpired as exc:
            raise RuntimeError('SAM3 timed out after 7 minutes; inspect GPU memory or run the worker directly.') from exc
        if run.returncode != 0:
            msg = (run.stderr or '')[-3500:] + '\n' + (run.stdout or '')[-1500:]
            raise RuntimeError(f'SAM3 worker failed (code {run.returncode}):\n{msg}')
        if not result.exists():
            raise RuntimeError(f'SAM3 worker did not produce a mask:\n{run.stdout}\n{run.stderr}')
        with Image.open(result) as mask:
            return mask.convert('L').copy()
